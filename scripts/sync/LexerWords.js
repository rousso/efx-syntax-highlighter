// The words of EFX-2, in the sets the highlighter needs. No word is typed in: the candidates are
// the quoted words of EfxLexer.g4, and the generated lexer and parser say which set each belongs
// to, by the token the lexer makes of it in each mode. The toolkit's CatalogueCompletenessTest
// reads the lexer's words the same way.

const QUOTED_WORD = /'([A-Za-z_][\w-]*)'/g;

// The modes in which the lexer reserves words outside label blocks and format options: the start
// of a line, the whitespace after a keyword, template text and expressions.
const KEYWORD_MODES = ['DEFAULT_MODE', 'SKIP_WHITESPACE', 'TEMPLATE', 'EXPRESSION'];

// The tokens a word becomes in those modes when the lexer does not reserve it.
const PLAIN_WORDS = new Set(['Identifier', 'FreeText']);

export class LexerWords {
  #grammar;
  #candidates;

  constructor(grammar, lexerGrammar) {
    this.#grammar = grammar;
    this.#candidates = [...new Set(Array.from(lexerGrammar.matchAll(QUOTED_WORD), (match) => match[1]))].sort();
  }

  functionNames() {
    const functionTokens = this.#grammar.firstTokens('builtInFunction');
    return this.#candidates.filter((word) => functionTokens.has(this.#grammar.tokenOf(word, 'EXPRESSION')));
  }

  keywords() {
    const functionNames = new Set(this.functionNames());
    return this.#candidates.filter((word) => !functionNames.has(word)
      && KEYWORD_MODES.some((mode) => this.#isReserved(word, mode)));
  }

  assetTypes() {
    return this.#candidates.filter((word) => this.#grammar.tokenOf(word, 'LABEL') === 'AssetType');
  }

  labelTypes() {
    return this.#candidates.filter((word) => this.#grammar.tokenOf(word, 'LABEL') === 'LabelType');
  }

  formatOptions() {
    return this.#candidates.filter((word) => this.#grammar.tokenOf(word, 'FORMAT') !== undefined);
  }

  /** The text of src/generated/words.js. */
  toModule(source) {
    return [
      `// Generated by \`npm run sync\` from EfxLexer.g4 and Efx.g4 at ${source}. Do not edit.`,
      LexerWords.#declaration('functionNames',
        'Every spelling of a token that can start a built-in function call (builtInFunction in Efx.g4).',
        this.functionNames()),
      LexerWords.#declaration('keywords',
        'Every other word the lexer reserves at the start of a line, in template text and in expressions.',
        this.keywords()),
      LexerWords.#declaration('assetTypes',
        'The words the lexer reads as AssetType in a label block.', this.assetTypes()),
      LexerWords.#declaration('labelTypes',
        'The words the lexer reads as LabelType in a label block.', this.labelTypes()),
      LexerWords.#declaration('formatOptions',
        'The words of the format options after the pipe of an expression block.', this.formatOptions()),
    ].join('\n\n') + '\n';
  }

  #isReserved(word, mode) {
    const token = this.#grammar.tokenOf(word, mode);
    return token !== undefined && !PLAIN_WORDS.has(token);
  }

  static #declaration(name, comment, words) {
    return `// ${comment}\nexport const ${name} = new Set([\n${words.map((word) => `  '${word}',`).join('\n')}\n]);`;
  }
}
