// The words of EFX-2, in the sets and tables the highlighter needs. No word is typed in: the
// candidates are the quoted words of EfxLexer.g4, and the generated lexer and parser say where each
// belongs, by the token the lexer makes of it in each mode. Like the toolkit's
// CatalogueCompletenessTest, it finds a word's token by lexing the word.

// The modes in which the lexer reserves words outside label blocks and format options: the start
// of a line, the whitespace after a keyword, template text and expressions.
const KEYWORD_MODES = ['DEFAULT_MODE', 'SKIP_WHITESPACE', 'TEMPLATE', 'EXPRESSION'];

// The modes of the words that start a line or come between its parts.
const LINE_MODES = ['DEFAULT_MODE', 'SKIP_WHITESPACE'];

// The whitespace the lexer reads between the two words of a phrase it makes one token of, such as
// OTHERWISE DISPLAY: (TAB | SPACE | EOL)+. A phrase is listed when every one of these gives its token.
const PHRASE_GAPS = [' ', '\t', '\n', ' \r\n\t '];

// The tokens a word becomes in those modes when the lexer does not reserve it.
const PLAIN_WORDS = new Set(['Identifier', 'FreeText']);

// The parser rule whose first tokens are the names of the built-in functions.
const FUNCTION_RULE = 'builtInFunction';

export class LexerWords {
  #grammar;
  #candidates;
  #sets;
  #tables;

  constructor(grammar) {
    this.#grammar = grammar;
    this.#candidates = grammar.quotedWords();
    const functionOnlyTokens = grammar.tokensReadOnlyAtStartOf(FUNCTION_RULE);
    this.#sets = [
      { name: 'keywords', words: this.#keywords(functionOnlyTokens),
        comment: 'Every word the lexer reads as a token of its own at the start of a line, in template text or in '
          + 'expressions, except the words the parser reads only as the name of a built-in function.' },
      { name: 'assetTypes', words: this.#lexedAs('LABEL', 'AssetType'),
        comment: 'The words the lexer reads as AssetType in a label block.' },
      { name: 'labelTypes', words: this.#lexedAs('LABEL', 'LabelType'),
        comment: 'The words the lexer reads as LabelType in a label block.' },
    ];
    this.#tables = [
      { name: 'lineTokens', tokens: this.#lineTokens(),
        comment: 'The token the lexer makes of each word it reserves at the start of a line or between its parts.' },
      { name: 'templateTokens', tokens: this.#tokensIn('TEMPLATE'),
        comment: 'The token the lexer makes of each word it reserves in template text.' },
      { name: 'formatTokens', tokens: this.#tokensIn('FORMAT'),
        comment: 'The token the lexer makes of each word of the format options after the pipe of an expression block.' },
      { name: 'expressionTokens', tokens: this.#tokensIn('EXPRESSION'),
        comment: 'The token the lexer makes of each word it reserves in an expression.' },
    ];
  }

  /** The text of src/generated/words.js. */
  toModule(source) {
    return [
      `// Generated by \`npm run sync\` from EfxLexer.g4 and Efx.g4 at ${source}. Do not edit.`,
      ...this.#sets.map(({ name, words, comment }) =>
        `// ${comment}\nexport const ${name} = new Set([\n${words.map((word) => `  '${word}',`).join('\n')}\n]);`),
      ...this.#tables.map(({ name, tokens, comment }) =>
        `// ${comment}\nexport const ${name} = new Map([\n`
          + `${[...tokens].map(([word, token]) => `  ['${word}', '${token}'],`).join('\n')}\n]);`),
    ].join('\n\n') + '\n';
  }

  /** The size of each set and table, for the sync's report. */
  toString() {
    return [
      ...this.#sets.map(({ name, words }) => `${words.length} ${name}`),
      ...this.#tables.map(({ name, tokens }) => `${tokens.size} ${name}`),
    ].join(', ');
  }

  #keywords(functionOnlyTokens) {
    return this.#candidates.filter((word) => !functionOnlyTokens.has(this.#grammar.tokenOf(word, 'EXPRESSION'))
      && KEYWORD_MODES.some((mode) => this.#isReserved(word, mode)));
  }

  #tokensIn(mode) {
    const tokens = new Map(this.#candidates.filter((word) => this.#isReserved(word, mode))
      .map((word) => [word, this.#reservedToken(word, mode)]));
    return this.#withPhrases(tokens, [mode]);
  }

  /**
   * A table of words with the phrases the lexer makes one token of in the given modes: a reserved
   * word, whitespace and another word, listed as the two words with one blank between them.
   */
  #withPhrases(tokens, modes) {
    const phrases = new Map();
    for (const first of tokens.keys()) {
      for (const second of this.#candidates) {
        const token = modes.map((mode) => this.#phraseToken(first, second, mode))
          .find((name) => name !== undefined);
        if (token !== undefined) {
          phrases.set(`${first} ${second}`, token);
        }
      }
    }
    return new Map([...tokens, ...phrases]);
  }

  /** The token the lexer makes of two words in a mode, the same whatever whitespace is between them. */
  #phraseToken(first, second, mode) {
    const [token, ...others] = PHRASE_GAPS.map((gap) => this.#reservedToken(`${first}${gap}${second}`, mode));
    return others.every((other) => other === token) ? token : undefined;
  }

  /**
   * The token of each word the lexer reserves at the start of a line or between its parts. A word is
   * also read with a blank after it, since the lexer reads DISPLAY at the start of a line as one
   * token with the whitespace that follows it.
   */
  #lineTokens() {
    const tokens = new Map();
    for (const word of this.#candidates) {
      const token = LINE_MODES.flatMap((mode) => [word, `${word} `].map((text) => this.#reservedToken(text, mode)))
        .find((name) => name !== undefined);
      if (token !== undefined) {
        tokens.set(word, token);
      }
    }
    return this.#withPhrases(tokens, LINE_MODES);
  }

  #lexedAs(mode, token) {
    return this.#lexedAsOneOf(mode, new Set([token]));
  }

  #lexedAsOneOf(mode, tokens) {
    return this.#candidates.filter((word) => tokens.has(this.#grammar.tokenOf(word, mode)));
  }

  #isReserved(word, mode) {
    return this.#reservedToken(word, mode) !== undefined;
  }

  /** The token the lexer makes of a text in a mode, when it is one token and not a plain word. */
  #reservedToken(text, mode) {
    const token = this.#grammar.tokenOf(text, mode);
    return PLAIN_WORDS.has(token) ? undefined : token;
  }
}
